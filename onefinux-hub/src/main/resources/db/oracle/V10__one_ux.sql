-- One UX platform: usage telemetry and feedback, per-user and per-team personalisation, grid write-back with
-- maker-checker, and the access register (last seen, granted access, requests, reviews).

-- Every app open, view launch, component use, experiment exposure and feedback note. Append-only.
CREATE TABLE ux_event (
  id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at           TIMESTAMP     NOT NULL,
  actor        VARCHAR2(80)   NOT NULL,
  team         VARCHAR2(40),                         -- the group unit the user worked in
  type         VARCHAR2(30)   NOT NULL,              -- APP_OPEN | VIEW_OPEN | COMPONENT_USE | SEARCH | ASSIST | EXPOSURE | CONVERSION | FEEDBACK
  app          VARCHAR2(120),                        -- route or app id
  component    VARCHAR2(120),
  variant      VARCHAR2(40),
  detail_json  VARCHAR2(4000)
);
CREATE INDEX idx_ux_event_at ON ux_event (at DESC);
CREATE INDEX idx_ux_event_type ON ux_event (type, at);

-- A user's saved layout and settings (desks, saved grids, theme, view). The browser keeps a cache only.
CREATE TABLE user_pref (
  subject      VARCHAR2(80)   NOT NULL,
  pref_key     VARCHAR2(40)   NOT NULL,
  json         CLOB          NOT NULL,
  updated_at   TIMESTAMP     NOT NULL,
  PRIMARY KEY (subject, pref_key)
);

-- A desk (or grid) a team shares: anyone in the team starts a new desk from it.
CREATE TABLE team_template (
  id           VARCHAR2(40)   PRIMARY KEY,
  team         VARCHAR2(40)   NOT NULL,
  kind         VARCHAR2(20)   NOT NULL,              -- desk | grid
  name         VARCHAR2(120)  NOT NULL,
  json         CLOB          NOT NULL,
  created_by   VARCHAR2(80)   NOT NULL,
  created_at   TIMESTAMP     NOT NULL
);
CREATE INDEX idx_team_template ON team_template (team, kind);

-- Edits made in a grid, submitted together. Maker-checker: a different user approves before it is applied.
CREATE TABLE writeback_change_set (
  id            VARCHAR2(40)   PRIMARY KEY,
  grid_id       VARCHAR2(80)   NOT NULL,
  grid_title    VARCHAR2(160),
  status        VARCHAR2(20)   NOT NULL,             -- PENDING | APPLIED | REJECTED
  maker         VARCHAR2(80)   NOT NULL,
  checker       VARCHAR2(80),
  approval      VARCHAR2(20)   NOT NULL,             -- maker-checker | none
  context_json  VARCHAR2(2000),
  changes_json  CLOB          NOT NULL,
  reason        VARCHAR2(400),
  created_at    TIMESTAMP     NOT NULL,
  decided_at    TIMESTAMP
);
CREATE INDEX idx_writeback_grid ON writeback_change_set (grid_id, status);

-- Access register. Last seen drives the inactivity lock; grants come from approved requests; reviews confirm or revoke.
CREATE TABLE access_seen (
  subject      VARCHAR2(80)   PRIMARY KEY,
  last_seen    TIMESTAMP     NOT NULL,
  suspended    NUMBER(1)       DEFAULT 0 NOT NULL,
  suspended_at TIMESTAMP
);

CREATE TABLE access_grant (
  id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject      VARCHAR2(80)   NOT NULL,
  kind         VARCHAR2(20)   NOT NULL,              -- ROLE | GROUP_UNIT | CEES
  grant_value  VARCHAR2(80)   NOT NULL,
  status       VARCHAR2(20)   NOT NULL,              -- ACTIVE | REVOKED
  source       VARCHAR2(80),                         -- the request id
  granted_by   VARCHAR2(80)   NOT NULL,
  granted_at   TIMESTAMP     NOT NULL,
  reviewed_by  VARCHAR2(80),
  reviewed_at  TIMESTAMP
);
CREATE INDEX idx_access_grant ON access_grant (subject, status);

CREATE TABLE access_request (
  id           VARCHAR2(40)   PRIMARY KEY,
  subject      VARCHAR2(80)   NOT NULL,
  target       VARCHAR2(160)  NOT NULL,              -- the desk or app the access is for
  items_json   VARCHAR2(2000) NOT NULL,
  reason       VARCHAR2(400),
  status       VARCHAR2(20)   NOT NULL,              -- PENDING | APPROVED | REJECTED
  requested_at TIMESTAMP     NOT NULL,
  decided_by   VARCHAR2(80),
  decided_at   TIMESTAMP
);

-- Demo: the auditor last visited 120 days ago, so their next request is suspended for inactivity (limit 90 days).
INSERT INTO access_seen (subject, last_seen, suspended, suspended_at)
VALUES ('auditor', CAST(CURRENT_TIMESTAMP AS TIMESTAMP) - INTERVAL '120' DAY, 0, NULL);

-- One UX platform: usage telemetry and feedback, per-user and per-team personalisation, grid write-back with
-- maker-checker, and the access register (last seen, granted access, requests, reviews).

-- Every app open, view launch, component use, experiment exposure and feedback note. Append-only.
CREATE TABLE IF NOT EXISTS ux_event (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at           TIMESTAMP     NOT NULL,
  actor        VARCHAR(80)   NOT NULL,
  team         VARCHAR(40),                         -- the group unit the user worked in
  type         VARCHAR(30)   NOT NULL,              -- APP_OPEN | VIEW_OPEN | COMPONENT_USE | SEARCH | ASSIST | EXPOSURE | CONVERSION | FEEDBACK
  app          VARCHAR(120),                        -- route or app id
  component    VARCHAR(120),
  variant      VARCHAR(40),
  detail_json  VARCHAR(4000)
);
CREATE INDEX IF NOT EXISTS idx_ux_event_at ON ux_event (at DESC);
CREATE INDEX IF NOT EXISTS idx_ux_event_type ON ux_event (type, at);

-- A user's saved layout and settings (desks, saved grids, theme, view). The browser keeps a cache only.
CREATE TABLE IF NOT EXISTS user_pref (
  subject      VARCHAR(80)   NOT NULL,
  pref_key     VARCHAR(40)   NOT NULL,
  json         CLOB          NOT NULL,
  updated_at   TIMESTAMP     NOT NULL,
  PRIMARY KEY (subject, pref_key)
);

-- A desk (or grid) a team shares: anyone in the team starts a new desk from it.
CREATE TABLE IF NOT EXISTS team_template (
  id           VARCHAR(40)   PRIMARY KEY,
  team         VARCHAR(40)   NOT NULL,
  kind         VARCHAR(20)   NOT NULL,              -- desk | grid
  name         VARCHAR(120)  NOT NULL,
  json         CLOB          NOT NULL,
  created_by   VARCHAR(80)   NOT NULL,
  created_at   TIMESTAMP     NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_team_template ON team_template (team, kind);

-- Edits made in a grid, submitted together. Maker-checker: a different user approves before it is applied.
CREATE TABLE IF NOT EXISTS writeback_change_set (
  id            VARCHAR(40)   PRIMARY KEY,
  grid_id       VARCHAR(80)   NOT NULL,
  grid_title    VARCHAR(160),
  status        VARCHAR(20)   NOT NULL,             -- PENDING | APPLIED | REJECTED
  maker         VARCHAR(80)   NOT NULL,
  checker       VARCHAR(80),
  approval      VARCHAR(20)   NOT NULL,             -- maker-checker | none
  context_json  VARCHAR(2000),
  changes_json  CLOB          NOT NULL,
  reason        VARCHAR(400),
  created_at    TIMESTAMP     NOT NULL,
  decided_at    TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_writeback_grid ON writeback_change_set (grid_id, status);

-- Access register. Last seen drives the inactivity lock; grants come from approved requests; reviews confirm or revoke.
CREATE TABLE IF NOT EXISTS access_seen (
  subject      VARCHAR(80)   PRIMARY KEY,
  last_seen    TIMESTAMP     NOT NULL,
  suspended    BOOLEAN       DEFAULT FALSE NOT NULL,
  suspended_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS access_grant (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject      VARCHAR(80)   NOT NULL,
  kind         VARCHAR(20)   NOT NULL,              -- ROLE | GROUP_UNIT | CEES
  grant_value  VARCHAR(80)   NOT NULL,
  status       VARCHAR(20)   NOT NULL,              -- ACTIVE | REVOKED
  source       VARCHAR(80),                         -- the request id
  granted_by   VARCHAR(80)   NOT NULL,
  granted_at   TIMESTAMP     NOT NULL,
  reviewed_by  VARCHAR(80),
  reviewed_at  TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_access_grant ON access_grant (subject, status);

CREATE TABLE IF NOT EXISTS access_request (
  id           VARCHAR(40)   PRIMARY KEY,
  subject      VARCHAR(80)   NOT NULL,
  target       VARCHAR(160)  NOT NULL,              -- the desk or app the access is for
  items_json   VARCHAR(2000) NOT NULL,
  reason       VARCHAR(400),
  status       VARCHAR(20)   NOT NULL,              -- PENDING | APPROVED | REJECTED
  requested_at TIMESTAMP     NOT NULL,
  decided_by   VARCHAR(80),
  decided_at   TIMESTAMP
);

-- Demo: the auditor last visited 120 days ago, so their next request is suspended for inactivity (limit 90 days).
MERGE INTO access_seen KEY (subject) VALUES ('auditor', DATEADD('DAY', -120, CURRENT_TIMESTAMP), FALSE, NULL);
